-- Gestion dans l'espace administrateur des packs et galeries de la page d'accueil.
-- Les visuels peuvent être téléversés depuis « Accueil — Packs et images ».

create table if not exists public.accueil_sections (
  id bigint generated by default as identity primary key,
  section text not null check (section in ('packs', 'mission', 'resultats')),
  item_type text not null check (item_type in ('pack', 'texte', 'image')),
  titre text not null,
  description text,
  surtitre text,
  texte_final text,
  image text,
  produit_id bigint references public.produits(id) on delete set null on update cascade,
  ordre integer not null default 0,
  actif boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_accueil_sections_order
  on public.accueil_sections (section, ordre);

alter table public.accueil_sections enable row level security;

drop policy if exists "anon_read_accueil_sections" on public.accueil_sections;
create policy "anon_read_accueil_sections" on public.accueil_sections
  for select to anon, authenticated using (actif = true);

drop policy if exists "admin_all_accueil_sections" on public.accueil_sections;
create policy "admin_all_accueil_sections" on public.accueil_sections
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

grant select on public.accueil_sections to anon, authenticated;
grant insert, update, delete on public.accueil_sections to authenticated;
grant usage, select on sequence public.accueil_sections_id_seq to authenticated;

drop trigger if exists accueil_sections_updated_at on public.accueil_sections;
create trigger accueil_sections_updated_at
  before update on public.accueil_sections
  for each row execute function public.set_updated_at();

