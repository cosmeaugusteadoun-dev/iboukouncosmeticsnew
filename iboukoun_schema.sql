create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admins
    where id = auth.uid() and actif = true and role = 'admin'
  );
$$;
grant execute on function public.is_admin() to anon, authenticated;

create or replace function public.save_product_photo(photo_id bigint, payload jsonb)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
  v_produit_id bigint;
  v_is_principale boolean;
begin
  if not public.is_admin() then
    raise exception 'Accès refusé';
  end if;
  v_produit_id := (payload->>'produit_id')::bigint;
  v_is_principale := coalesce((payload->>'is_principale')::boolean, false);

  if photo_id is null then
    insert into public.produit_photos (produit_id, fichier, legende, ordre, is_principale, actif)
    values (
      v_produit_id,
      payload->>'fichier',
      payload->>'legende',
      coalesce((payload->>'ordre')::integer, 0),
      v_is_principale,
      coalesce((payload->>'actif')::boolean, true)
    )
    returning id into v_id;
  else
    update public.produit_photos
    set produit_id = v_produit_id,
        fichier = payload->>'fichier',
        legende = payload->>'legende',
        ordre = coalesce((payload->>'ordre')::integer, 0),
        is_principale = v_is_principale,
        actif = coalesce((payload->>'actif')::boolean, true),
        updated_at = now()
    where id = photo_id
    returning id into v_id;
  end if;

  if v_is_principale then
    update public.produit_photos
    set is_principale = false
    where produit_id = v_produit_id and id <> v_id;
  end if;

  return v_id;
end;
$$;
grant execute on function public.save_product_photo(bigint, jsonb) to authenticated;

